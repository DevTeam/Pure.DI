/*
$v=true
$p=0
$d=Resolve hint
$sa=Resolve methods
$sa=Check for a root
$h=Hints fine-tune code generation. The `Resolve` hint decides whether the composition gets dynamic entry points: `Resolve<T>()`, `Resolve(Type)` and their tagged overloads, four members in total, generated by default.
$h=Set it to `Off` when a composition exposes named roots only, which is the usual setting for an application: generation gets cheaper, no anonymous roots are emitted, and the public API of the composition stays limited to the members you declared. Only regular root properties and methods remain, so declare every entry point with `Root<T>(...)`.
$h=Keep it `On` for a host that resolves types it learns about at runtime, such as a plugin or script host, and for exploratory tests. A hint can also be a comment before `Setup`: `// Resolve = Off`.
$f=In a real project the hint belongs to the composition in the startup or integration assembly; a library usually ships bindings and lets the application decide.
$f=A root that needs a root argument cannot be produced by a `Resolve` method. Pure.DI still generates the methods and reports a warning, so prefer `// Resolve = Off` in such compositions instead of living with it.
$f=With the hint `Off`, an unnamed `Root<T>()` is not emitted at all, and an unused private root is easy to miss because nothing fails to compile.
$f=`Resolve` for a type with no root throws `CannotResolveException` at runtime, so the safety of a `Resolve` call is exactly the root list behind it.
$f=Prefer named roots whenever the entry points are known at compile time; [Resolve methods](resolve-methods.md) shows what the dynamic path costs.
$f=For more hints, see [this](../README.md#setup-hints) page.
*/

